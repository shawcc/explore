def main():
    workbook = load_workbook(SOURCE)
    sheet = workbook["场景产品关系表"]
    headers = [cell.value for cell in sheet[1]]

    if "PRD正文" not in headers:
        insert_at = headers.index("PRD链接") + 1
        sheet.insert_cols(insert_at)
        sheet.cell(1, insert_at, "PRD正文")
        headers = [cell.value for cell in sheet[1]]

    positions = {name: index for index, name in enumerate(headers)}
    updated = []
    for row in sheet.iter_rows(min_row=2):
        scenario_id = row[positions["场景ID"]].value
        if scenario_id in PRDS and row[positions["是否主要实现"]].value == "是":
            row[positions["PRD正文"]].value = PRDS[scenario_id]
            updated.append(scenario_id)

    if set(updated) != set(PRDS):
        raise RuntimeError(f"Expected {sorted(PRDS)}, updated {sorted(updated)}")

    workbook.save(SOURCE)
    print({"updated": updated, "source": str(SOURCE)})


if __name__ == "__main__":
    main()
